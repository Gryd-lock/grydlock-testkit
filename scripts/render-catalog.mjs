#!/usr/bin/env node
// Renders docs/FIXTURES.md — one row per destination and transaction with its
// label, risk pattern, rationale and testnet explorer link — from the data
// files. `npm run docs` rewrites it; tests/catalog.test.mjs fails if the
// committed file has drifted from the data.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const short = (id) => (id.length > 20 ? `${id.slice(0, 6)}…${id.slice(-4)}` : id);
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderCatalog(root = ROOT) {
  const destinations = JSON.parse(readFileSync(join(root, 'destinations.json'), 'utf-8')).destinations;
  const scores = JSON.parse(readFileSync(join(root, 'scores.json'), 'utf-8'));
  const index = JSON.parse(readFileSync(join(root, 'transactions/index.json'), 'utf-8'));
  const order = { clean: 0, suspicious: 1, malicious: 2 };
  const byLabel = (a, b) => order[a.label] - order[b.label];
  const count = (xs, l) => xs.filter((x) => x.label === l).length;

  const destRows = [...destinations].sort(byLabel).map((d) => {
    const link = d.provenance?.explorer ? `[${short(d.id)}](${d.provenance.explorer})` : `\`${short(d.id)}\``;
    return `| ${link} | ${d.type} | ${d.persona ?? ''} | **${d.label}** | ${d.risk_pattern} | ${scores[d.id]} | ${d.provenance?.kind} | ${cell(d.rationale)} |`;
  });
  const txRows = [...index.fixtures].sort(byLabel).map((f) => {
    const link = f.provenance?.explorer ? `[${f.stellarHashTestnet.slice(0, 10)}…](${f.provenance.explorer})` : 'offline';
    const ops = f.operations.map((o) => (o.method ? `${o.type}:${o.method}` : o.type)).join(', ');
    return `| \`${f.id}\` | **${f.label}** | ${f.risk_pattern} | ${ops} | ${link} | ${cell(f.rationale)} |`;
  });

  return `<!-- Generated by scripts/render-catalog.mjs (npm run docs). Do not edit by hand. -->
# Fixture catalog

Every labelled fixture, with the rationale for its label. Taxonomy and rubric: [LABELS.md](LABELS.md).
Testnet links resolve on stellar.expert until the next testnet reset (see the README).

## Destinations (${destinations.length})

${count(destinations, 'clean')} clean · ${count(destinations, 'suspicious')} suspicious · ${count(destinations, 'malicious')} malicious

| Id | Type | Persona | Label | Risk pattern | Stub score | Provenance | Rationale |
| --- | --- | --- | --- | --- | ---: | --- | --- |
${destRows.join('\n')}

## Transactions (${index.fixtures.length})

${count(index.fixtures, 'clean')} clean · ${count(index.fixtures, 'suspicious')} suspicious · ${count(index.fixtures, 'malicious')} malicious

| Fixture | Label | Risk pattern | Operations | Testnet tx | Rationale |
| --- | --- | --- | --- | --- | --- |
${txRows.join('\n')}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(ROOT, 'docs/FIXTURES.md'), renderCatalog());
  console.log('wrote docs/FIXTURES.md');
}
