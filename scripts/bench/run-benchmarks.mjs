/**
 * Fixture-loading benchmark harness.
 *
 * Usage:
 *   node scripts/bench/run-benchmarks.mjs
 *   node scripts/bench/run-benchmarks.mjs --sizes 12,100,1000,10000,100000
 *   node scripts/bench/run-benchmarks.mjs --strategies raw-json,split-packs --repeat 5
 *
 * For every (corpus size, strategy) pair it builds the artifact a release
 * would ship, then measures load and lookup cost in a fresh child process
 * (`measure.mjs`). Results are written to `.bench/results.json` and
 * `.bench/results.md`; `.bench/` is git-ignored.
 *
 * Everything is deterministic apart from the timings themselves, and each
 * timing is the median of `--repeat` independent processes.
 */

import { execFileSync } from 'node:child_process';
import { cpus, totalmem } from 'node:os';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_SIZES, writeCorpus } from './generate-corpus.mjs';
import { STRATEGIES, getStrategy } from './strategies.mjs';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const MEASURE = fileURLToPath(new URL('./measure.mjs', import.meta.url));

function parseArgs(argv) {
  const args = {
    sizes: DEFAULT_SIZES,
    strategies: STRATEGIES.map((s) => s.id),
    repeat: 3,
    out: '.bench'
  };
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    if (flag === '--sizes') {
      args.sizes = argv[++i]
        .split(',')
        .map((s) => Number.parseInt(s.trim(), 10))
        .filter((n) => Number.isInteger(n) && n > 0);
    } else if (flag === '--strategies') {
      args.strategies = argv[++i].split(',').map((s) => s.trim());
    } else if (flag === '--repeat') {
      args.repeat = Math.max(1, Number.parseInt(argv[++i], 10));
    } else if (flag === '--out') {
      args.out = argv[++i];
    } else {
      throw new Error(`unknown flag "${flag}"`);
    }
  }
  return args;
}

function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  const mid = sorted.length >> 1;
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
}

function measureOnce(strategyId, artifactDir, corpusDir) {
  const stdout = execFileSync(
    process.execPath,
    ['--expose-gc', MEASURE, strategyId, artifactDir, corpusDir],
    { encoding: 'utf-8', stdio: ['ignore', 'pipe', 'inherit'] }
  );
  return JSON.parse(stdout);
}

const NUMERIC_KEYS = [
  'coldLoadMs',
  'warmLoadMs',
  'firstLookupUs',
  'sessionMs',
  'hitLookupNs',
  'missLookupNs',
  'heapAfterLoadBytes',
  'heapAfterSessionBytes',
  'heapAfterHitsBytes'
];

function aggregate(runs) {
  const out = { ...runs[0] };
  for (const key of NUMERIC_KEYS) {
    out[key] = median(runs.map((r) => r[key]));
  }
  out.correct = runs.every((r) => r.correct);
  out.prototypeSafe = runs.every((r) => r.prototypeSafe);
  delete out.checksum;
  return out;
}

const kb = (bytes) => (bytes / 1024).toFixed(1);
const ms = (value) => value.toFixed(3);
const ns = (value) => value.toFixed(1);

function toMarkdown(report) {
  const lines = [];
  lines.push('# Fixture-loading benchmark results');
  lines.push('');
  lines.push(`Generated by \`npm run bench\` on ${report.environment.date}.`);
  lines.push('');
  lines.push(
    `Node ${report.environment.node} | ${report.environment.platform}/${report.environment.arch} | ` +
      `${report.environment.cpu} | ${report.environment.totalMemGb} GB RAM | ` +
      `${report.repeat === 1 ? '1 process' : `median of ${report.repeat} processes`} per cell`
  );
  lines.push('');

  for (const size of report.sizes) {
    const rows = report.results.filter((r) => r.entries === size);
    if (rows.length === 0) continue;
    lines.push(`## ${size.toLocaleString('en-US')} entries`);
    lines.push('');
    lines.push(
      '| Strategy | Cold load (ms) | Warm load (ms) | Hit lookup (ns) | Miss lookup (ns) | ' +
        'Heap after load (KB) | Startup bytes | Total bytes | Total gzip |'
    );
    lines.push('|---|---:|---:|---:|---:|---:|---:|---:|---:|');
    for (const r of rows) {
      lines.push(
        `| ${r.label} | ${ms(r.coldLoadMs)} | ${ms(r.warmLoadMs)} | ${ns(r.hitLookupNs)} | ` +
          `${ns(r.missLookupNs)} | ${kb(r.heapAfterLoadBytes)} | ${kb(r.artifact.initialBytes)} | ` +
          `${kb(r.artifact.totalBytes)} | ${kb(r.artifact.totalGzipBytes)} |`
      );
    }
    lines.push('');
    lines.push(
      `Cold session (load + ${rows[0].sessionLookups} distinct lookups), which is what one ` +
        'extension session actually pays:'
    );
    lines.push('');
    lines.push('| Strategy | Session (ms) | Heap after session (KB) | Bytes pulled | Shards pulled |');
    lines.push('|---|---:|---:|---:|---:|');
    for (const r of rows) {
      lines.push(
        `| ${r.label} | ${ms(r.sessionMs)} | ${kb(r.heapAfterSessionBytes)} | ` +
          `${r.sessionTouchedBytes === null ? 'all' : kb(r.sessionTouchedBytes) + ' KB'} | ` +
          `${r.sessionShards === null ? 'n/a' : r.sessionShards} |`
      );
    }
    lines.push('');
  }

  lines.push('## Notes');
  lines.push('');
  for (const r of report.results) {
    if (!r.correct) lines.push(`- ${r.label} @ ${r.entries}: FAILED the correctness check.`);
    if (!r.prototypeSafe) {
      lines.push(
        `- ${r.label} @ ${r.entries}: not prototype-safe - inherited keys such as \`constructor\` resolve to a value instead of \`undefined\`.`
      );
    }
    if (r.lazyTouchedBytes !== null) {
      lines.push(
        `- ${r.label} @ ${r.entries}: pulled ${kb(r.lazyTouchedBytes)} KB across ${r.loadedShards} shard(s) to answer a 512-ID working set (vs ${kb(r.sessionTouchedBytes)} KB / ${r.sessionShards} shard(s) for a ${r.sessionLookups}-ID session); first lookup cost ${r.firstLookupUs.toFixed(1)} us.`
      );
    }
  }
  lines.push('');
  return lines.join('\n');
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const outRoot = join(ROOT, args.out);
  mkdirSync(outRoot, { recursive: true });

  const results = [];
  const sizes = [];

  for (const requested of args.sizes) {
    const corpus = writeCorpus(requested, outRoot);
    sizes.push(corpus.size);
    console.log(`\ncorpus: ${corpus.size} entries (${corpus.synthetic ? 'synthetic' : 'real baseline'})`);

    for (const strategyId of args.strategies) {
      const strategy = getStrategy(strategyId);
      const artifactDir = join(outRoot, `artifacts-${corpus.size}`, strategyId);
      const artifact = strategy.build(corpus.dir, artifactDir);

      const runs = [];
      for (let i = 0; i < args.repeat; i++) {
        runs.push(measureOnce(strategyId, artifactDir, corpus.dir));
      }
      const result = { ...aggregate(runs), label: strategy.label, artifact };
      results.push(result);

      console.log(
        `  ${strategy.label.padEnd(36)} load ${ms(result.coldLoadMs).padStart(8)} ms | ` +
          `hit ${ns(result.hitLookupNs).padStart(7)} ns | heap ${kb(result.heapAfterLoadBytes).padStart(9)} KB | ` +
          `ship ${kb(result.artifact.totalGzipBytes).padStart(8)} KB gz${result.correct ? '' : '  [INCORRECT]'}`
      );
    }
  }

  const report = {
    environment: {
      date: new Date().toISOString().slice(0, 10),
      node: process.version,
      platform: process.platform,
      arch: process.arch,
      cpu: cpus()[0]?.model.trim() ?? 'unknown',
      totalMemGb: Math.round(totalmem() / 1024 ** 3)
    },
    repeat: args.repeat,
    sizes,
    results
  };

  writeFileSync(join(outRoot, 'results.json'), JSON.stringify(report, null, 2) + '\n');
  writeFileSync(join(outRoot, 'results.md'), toMarkdown(report));
  console.log(`\nWrote ${join(args.out, 'results.json')} and ${join(args.out, 'results.md')}`);
}

main();
